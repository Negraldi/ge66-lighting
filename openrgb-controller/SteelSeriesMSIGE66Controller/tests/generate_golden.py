#!/usr/bin/env python3
# Generates golden.inc from the Python reference (ge66_lighting) at the root of this repository.
# The packets are the same ones `ge66-light --dry-run` prints, with the full payload.
#
# usage: generate_golden.py /path/to/this/repository > golden.inc
import sys

sys.path.insert(0, sys.argv[1])

from ge66_lighting import effect, keyboard, lightbar, model, profile  # noqa: E402


def bar(lighting, persist=False):
    return profile.build_lightbar({"lighting": lighting}, persist=persist)


def kb(lighting, persist=False):
    return profile.build_keyboard({"lighting": lighting}, persist=persist)


def fx(kind, colors, **extra):
    spec = {"kind": kind, "colors": colors, "speed": 200}
    spec.update(extra)
    return spec


def effect_lighting(spec):
    return {"type": "effect", "effect": spec, "slot": 0, "base": "000000"}


RAINBOW = "rainbow"
ZONE_COLORS = {z: ((z * 7) % 256, 255 - z * 5, (z * 3) % 256) for z in range(lightbar.ZONES)}
KEY_COLORS = {code: ((code * 5) % 256, (code * 11) % 256, 255 - code) for code in keyboard.PHYSICAL}
HOST_STREAM = model.ElementInfo(settings_mask=model.MASK_HOST_STREAM)
FOURTEEN = [[(i * 18) % 256, (i * 37) % 256, (i * 91) % 256] for i in range(14)]
EIGHT = [[255, 0, 0], [255, 128, 0], [255, 255, 0], [0, 255, 0], [0, 255, 255], [0, 0, 255], [128, 0, 255], [255, 0, 255]]

CASES = [
    ("bar_fw_version", [lightbar.fw_version_request()]),
    ("bar_brightness_ff", [lightbar.global_brightness(0xFF)]),
    ("bar_brightness_80", [lightbar.global_brightness(0x80)]),
    ("bar_color_scale", [lightbar.color_scale()]),
    ("bar_save_to_flash", [lightbar.save_to_flash()]),
    ("bar_reset_current_lighting_mode", [lightbar.reset_current_lighting_mode()]),
    ("kb_fw_version", [keyboard.fw_version_request()]),
    ("kb_color_scale", [keyboard.color_scale()]),
    ("bar_direct_write_full", [lightbar.direct_write(ZONE_COLORS)]),
    ("bar_static_red", bar({"type": "static", "color": "ff0000"})),
    ("bar_static_persist", bar({"type": "static", "color": "123456"}, persist=True)),
    ("bar_off", bar({"type": "off"})),
    ("bar_stream_init", [lightbar.zone_table([HOST_STREAM] * lightbar.ZONES), lightbar.reset_current_lighting_mode()]),
    ("bar_colorshift_rainbow_horizontal", bar(effect_lighting(fx("colorshift", RAINBOW, direction="horizontal")))),
    ("bar_colorshift_rainbow_no_direction", bar(effect_lighting(fx("colorshift", RAINBOW)))),
    ("bar_colorshift_vertical_inverted", bar(effect_lighting(
        fx("colorshift", RAINBOW, direction="vertical", invert=True, focal=[4, 9], speed=333)))),
    ("bar_colorshift_radial_persist", bar(effect_lighting(
        fx("colorshift", RAINBOW, direction="radial", scale=77)), persist=True)),
    ("bar_colorshift_hold_section", bar(effect_lighting(
        fx("colorshift", [[255, 0, 0], [0, 255, 0], [0, 0, 255]], positions=[10, 50, 90])))),
    ("bar_colorshift_14_colors", bar(effect_lighting(fx("colorshift", FOURTEEN, speed=1200)))),
    ("bar_breathe_two_colors", bar(effect_lighting(fx("breathe", [[255, 0, 0], [0, 0, 255]], speed=300)))),
    ("bar_breathe_wave_inverted", bar(effect_lighting(
        fx("breathe", [[255, 0, 0], [0, 255, 0], [0, 0, 255]], direction="horizontal", invert=True,
           focal=[3, 5], speed=400)))),
    ("bar_breathe_8_colors", bar(effect_lighting(fx("breathe", EIGHT, speed=900)))),
    ("kb_static_red", kb({"type": "static", "color": "ff0000"})),
    ("kb_static_persist", kb({"type": "static", "color": "00ff80"}, persist=True)),
    ("kb_off", kb({"type": "off"})),
    ("kb_stream_init", keyboard.stream_init_sequence()),
    ("kb_direct_write_full", [keyboard.direct_write(KEY_COLORS)]),
    ("kb_colorshift_rainbow", kb(effect_lighting(fx("colorshift", RAINBOW)))),
    ("kb_breathe_three_colors", kb(effect_lighting(fx("breathe", [[255, 0, 0], [0, 255, 0], [0, 0, 255]], speed=640)))),
    ("kb_reactive_default_time", kb({"type": "reactive", "color": "000020", "react_color": "ffffff"})),
    ("kb_reactive_500_persist", kb({"type": "reactive", "color": "102030", "react_color": "ff8000",
                                   "react_time": 500}, persist=True)),
]

print("/* Generated by generate_golden.py from the ge66_lighting Python reference. Do not edit. */")
print("/* Each packet is a kind letter (O output 64 bytes, F feature 524 bytes) and the payload hex")
print("   without trailing zero bytes. */")
print("static const msige66_golden golden_cases[] =")
print("{")
for name, packets in CASES:
    print(f'    {{ "{name}",')
    print("        {")
    for packet in packets:
        letter = "O" if packet.kind == "output" else "F"
        print(f'            "{letter}{packet.data.rstrip(bytes(1)).hex()}",')
    print("            NULL")
    print("        }")
    print("    },")
print("};")
print()
print("static const char* golden_positions[] =")
print("{")
for count in range(1, 15):
    print(f'    "{bytes(effect.default_positions(count)).hex()}",')
print("};")
